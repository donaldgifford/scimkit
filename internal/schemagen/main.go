// Command schemagen generates scim/schema_gen.go from the vendored RFC 7643
// §8.7 schema JSON documents. It is invoked by go:generate from the scim
// package directory:
//
//	go run github.com/donaldgifford/scimkit/internal/schemagen
//
// Each schema document is decoded with scim.ParseSchema (which applies the
// §2.2 attribute defaults) and re-emitted as a Go composite literal inside an
// accessor function, so importing scim performs no JSON parsing at runtime
// and every accessor call returns a fresh, independently mutable value.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"

	"github.com/donaldgifford/scimkit/scim"
)

// schemaAccessor pairs a vendored fixture with the accessor emitted for it.
type schemaAccessor struct {
	file string // fixture under the schemas dir
	fn   string // generated accessor name
	doc  string // accessor doc comment body
}

var accessors = []schemaAccessor{
	{"user.json", "UserSchema", "the RFC 7643 §4.1 User schema"},
	{"group.json", "GroupSchema", "the RFC 7643 §4.2 Group schema"},
	{"enterprise-user.json", "EnterpriseUserSchema", "the RFC 7643 §4.3 Enterprise User extension schema"},
	{"service-provider-config.json", "ServiceProviderConfigSchema", "the RFC 7643 §5 ServiceProviderConfig schema"},
	{"resource-type.json", "ResourceTypeSchema", "the RFC 7643 §6 ResourceType schema"},
	{"schema.json", "SchemaMetaSchema", "the RFC 7643 §7 Schema meta-schema"},
}

func main() {
	log.SetFlags(0)
	log.SetPrefix("schemagen: ")

	inDir := "schemas"
	outFile := "schema_gen.go"
	if len(os.Args) > 1 {
		inDir = os.Args[1]
	}
	if len(os.Args) > 2 {
		outFile = os.Args[2]
	}

	var buf bytes.Buffer
	buf.WriteString("// Code generated by internal/schemagen from scim/schemas/*.json; DO NOT EDIT.\n\n")
	buf.WriteString("package scim\n")

	for _, acc := range accessors {
		data, err := os.ReadFile(filepath.Join(inDir, acc.file))
		if err != nil {
			log.Fatalf("read fixture: %v", err)
		}
		s, err := scim.ParseSchema(data)
		if err != nil {
			log.Fatalf("parse %s: %v", acc.file, err)
		}
		fmt.Fprintf(&buf, "\n// %s returns %s with the RFC 7643 §2.2 attribute\n", acc.fn, acc.doc)
		fmt.Fprintf(&buf, "// defaults applied. Each call returns a fresh value that is safe to modify.\n")
		fmt.Fprintf(&buf, "func %s() Schema {\n\treturn %s\n}\n", acc.fn, schemaLit(s, 1))
	}

	src, err := format.Source(buf.Bytes())
	if err != nil {
		log.Fatalf("format generated source: %v", err)
	}
	if err := os.WriteFile(outFile, src, 0o644); err != nil {
		log.Fatalf("write %s: %v", outFile, err)
	}
	log.Printf("wrote %s (%d schemas)", outFile, len(accessors))
}

var attrTypeIdent = map[scim.AttrType]string{
	scim.TypeString:    "TypeString",
	scim.TypeBoolean:   "TypeBoolean",
	scim.TypeDecimal:   "TypeDecimal",
	scim.TypeInteger:   "TypeInteger",
	scim.TypeDateTime:  "TypeDateTime",
	scim.TypeBinary:    "TypeBinary",
	scim.TypeReference: "TypeReference",
	scim.TypeComplex:   "TypeComplex",
}

var mutabilityIdent = map[scim.Mutability]string{
	scim.MutabilityReadOnly:  "MutabilityReadOnly",
	scim.MutabilityReadWrite: "MutabilityReadWrite",
	scim.MutabilityImmutable: "MutabilityImmutable",
	scim.MutabilityWriteOnly: "MutabilityWriteOnly",
}

var returnedIdent = map[scim.Returned]string{
	scim.ReturnedAlways:  "ReturnedAlways",
	scim.ReturnedNever:   "ReturnedNever",
	scim.ReturnedDefault: "ReturnedDefault",
	scim.ReturnedRequest: "ReturnedRequest",
}

var uniquenessIdent = map[scim.Uniqueness]string{
	scim.UniquenessNone:   "UniquenessNone",
	scim.UniquenessServer: "UniquenessServer",
	scim.UniquenessGlobal: "UniquenessGlobal",
}

func schemaLit(s scim.Schema, depth int) string {
	ind := tabs(depth)
	var b bytes.Buffer
	b.WriteString("Schema{\n")
	fmt.Fprintf(&b, "%s\tID:          %q,\n", ind, s.ID)
	if s.Name != "" {
		fmt.Fprintf(&b, "%s\tName:        %q,\n", ind, s.Name)
	}
	if s.Description != "" {
		fmt.Fprintf(&b, "%s\tDescription: %q,\n", ind, s.Description)
	}
	fmt.Fprintf(&b, "%s\tAttributes: []Attribute{\n", ind)
	for i := range s.Attributes {
		fmt.Fprintf(&b, "%s\t\t%s,\n", ind, attrLit(&s.Attributes[i], depth+2))
	}
	fmt.Fprintf(&b, "%s\t},\n", ind)
	fmt.Fprintf(&b, "%s}", ind)
	return b.String()
}

// attrLit renders an Attribute composite literal. Zero-valued booleans and
// nil slices are omitted; the enum characteristics are always explicit
// because ParseSchema guarantees they are non-zero after defaulting.
func attrLit(a *scim.Attribute, depth int) string {
	ind := tabs(depth)
	var b bytes.Buffer
	b.WriteString("{\n")
	fmt.Fprintf(&b, "%s\tName:        %q,\n", ind, a.Name)
	fmt.Fprintf(&b, "%s\tType:        %s,\n", ind, attrTypeIdent[a.Type])
	if a.MultiValued {
		fmt.Fprintf(&b, "%s\tMultiValued: true,\n", ind)
	}
	if a.Description != "" {
		fmt.Fprintf(&b, "%s\tDescription: %q,\n", ind, a.Description)
	}
	if a.Required {
		fmt.Fprintf(&b, "%s\tRequired:    true,\n", ind)
	}
	if len(a.CanonicalValues) > 0 {
		fmt.Fprintf(&b, "%s\tCanonicalValues: %#v,\n", ind, a.CanonicalValues)
	}
	if a.CaseExact {
		fmt.Fprintf(&b, "%s\tCaseExact:   true,\n", ind)
	}
	fmt.Fprintf(&b, "%s\tMutability:  %s,\n", ind, mutabilityIdent[a.Mutability])
	fmt.Fprintf(&b, "%s\tReturned:    %s,\n", ind, returnedIdent[a.Returned])
	fmt.Fprintf(&b, "%s\tUniqueness:  %s,\n", ind, uniquenessIdent[a.Uniqueness])
	if len(a.ReferenceTypes) > 0 {
		fmt.Fprintf(&b, "%s\tReferenceTypes: %#v,\n", ind, a.ReferenceTypes)
	}
	if len(a.SubAttributes) > 0 {
		fmt.Fprintf(&b, "%s\tSubAttributes: []Attribute{\n", ind)
		for i := range a.SubAttributes {
			fmt.Fprintf(&b, "%s\t\t%s,\n", ind, attrLit(&a.SubAttributes[i], depth+2))
		}
		fmt.Fprintf(&b, "%s\t},\n", ind)
	}
	fmt.Fprintf(&b, "%s}", ind)
	return b.String()
}

func tabs(n int) string {
	return string(bytes.Repeat([]byte{'\t'}, n))
}
